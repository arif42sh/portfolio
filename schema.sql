-- 1. Create Profile Table
CREATE TABLE IF NOT EXISTS public.profile (
  id INT PRIMARY KEY DEFAULT 1,
  name TEXT NOT NULL DEFAULT 'Arif Shahriar',
  eyebrow TEXT DEFAULT 'CSE Student • Cyber Security Enthusiast • AI & Software Developer',
  hero_sub TEXT DEFAULT 'I am passionate about Cyber Security, AI, software Development, and creating practical solutions with various technologies.',
  currently_exploring TEXT DEFAULT 'Networking Fundamentals & Linux Security',
  profile_image TEXT DEFAULT 'profile.png',
  resume_url TEXT DEFAULT 'resume.txt',
  email TEXT DEFAULT 'arifshahriar85204@gmail.com',
  github_url TEXT DEFAULT 'https://github.com/arif42sh',
  linkedin_url TEXT DEFAULT 'https://www.linkedin.com',
  facebook_url TEXT DEFAULT 'https://facebook.com',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create Projects Table
CREATE TABLE IF NOT EXISTS public.projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  badge TEXT DEFAULT 'Project',
  description TEXT NOT NULL,
  tech_stack TEXT[] DEFAULT '{}',
  bullets TEXT[] DEFAULT '{}',
  image_url TEXT DEFAULT '',
  github_url TEXT DEFAULT '',
  demo_url TEXT DEFAULT '',
  order_index INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create Skills Table
CREATE TABLE IF NOT EXISTS public.skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL, -- 'Languages', 'Frameworks', 'Database', 'Tools', 'Machine Learning'
  name TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.skills ENABLE ROW LEVEL SECURITY;

-- 5. Policies for Read and Write
DROP POLICY IF EXISTS "Public can view profile" ON public.profile;
DROP POLICY IF EXISTS "Admin can update profile" ON public.profile;
CREATE POLICY "Full access to profile" ON public.profile FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public can view projects" ON public.projects;
DROP POLICY IF EXISTS "Admin can manage projects" ON public.projects;
CREATE POLICY "Full access to projects" ON public.projects FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public can view skills" ON public.skills;
DROP POLICY IF EXISTS "Admin can manage skills" ON public.skills;
CREATE POLICY "Full access to skills" ON public.skills FOR ALL USING (true) WITH CHECK (true);

